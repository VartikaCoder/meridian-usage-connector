// Reproducible transcript of the three cases the brief asks to demonstrate, driven over real
// stdio MCP against the bundled server (the same file the plugin and Claude Desktop run).
//
//   make serve ENV=prod                  # in another terminal: the prod service on :8002
//   npm run bundle && npm run demo > ../docs/demo-transcript.md
import { fileURLToPath } from "node:url";
import { Client } from "@modelcontextprotocol/sdk/client/index.js";
import { StdioClientTransport } from "@modelcontextprotocol/sdk/client/stdio.js";

const BUNDLE = fileURLToPath(new URL("../dist/bundle/index.mjs", import.meta.url));
const SERVICE = process.env.MERIDIAN_SERVICE_URL ?? "http://127.0.0.1:8002";
const AS = process.env.MERIDIAN_USER ?? "priya.nair@meridianls.example";

interface Step {
  title: string;
  asked: string;
  tool: string;
  args: Record<string, unknown>;
}

const steps: Step[] = [
  {
    title: "1. Allowed read: a team lead asks about their own team",
    asked: "How much did my team use last month?",
    tool: "usage_summary",
    args: { period: "2026-09" },
  },
  {
    title: "2. Denied cross-group read",
    asked: "Who are the top users in Finance this month?",
    tool: "top_users",
    args: { group: "finance", period: "2026-09", limit: 5 },
  },
  {
    title: "3. Denied write",
    asked: "Turn off web search for my team.",
    tool: "set_capability",
    args: { group: "clinical-operations", capability: "web-search", enabled: false },
  },
];

async function main(): Promise<void> {
  const health = await fetch(`${SERVICE}/healthz`).catch(() => null);
  if (!health?.ok) throw new Error(`usage service not reachable at ${SERVICE}; run make serve ENV=prod`);
  const env = ((await health.json()) as { environment: string }).environment;

  const transport = new StdioClientTransport({
    command: process.execPath,
    args: [BUNDLE],
    env: {
      ...(process.env as Record<string, string>),
      MERIDIAN_USER: AS,
      MERIDIAN_SERVICE_URL: SERVICE,
      MERIDIAN_SERVER_NAME: "meridian-usage",
    },
  });
  const client = new Client({ name: "meridian-demo", version: "0.1.0" });
  await client.connect(transport);

  const out: string[] = [
    "# Demo transcript: Meridian usage connector",
    "",
    `Generated by \`npm run demo\` against the **${env}** service. The MCP client starts the`,
    "bundled server over stdio exactly as Claude Desktop does, acting as",
    `\`${AS}\` (team lead, clinical-operations). Each step shows the tool call a model would`,
    "make for the question, and the server's verbatim answer.",
    "",
    "## Tools the server offers",
    "",
  ];
  const { tools } = await client.listTools();
  for (const t of tools) out.push(`- \`${t.name}\`: ${t.description ?? ""}`);

  for (const s of steps) {
    const r = (await client.callTool({ name: s.tool, arguments: s.args })) as {
      content?: { type: string; text?: string }[];
      isError?: boolean;
    };
    out.push(
      "",
      `## ${s.title}`,
      "",
      `> ${s.asked}`,
      "",
      `Call: \`${s.tool}(${JSON.stringify(s.args)})\``,
      "",
      `Result (${r.isError ? "error result" : "success"}):`,
      "",
      "```json",
      r.content?.[0]?.text ?? "",
      "```",
    );
  }
  await client.close();
  console.log(out.join("\n"));
}

main().catch((err: unknown) => {
  console.error(err instanceof Error ? err.message : String(err));
  process.exit(1);
});
